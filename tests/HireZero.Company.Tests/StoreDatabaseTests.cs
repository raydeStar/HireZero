using System.Text.Json;
using HireZero.Core;
using HireZero.Integrations.Postgres;
using Microsoft.Data.Sqlite;
using Npgsql;

// One schema, two databases (docs/adr/0025-one-schema-two-databases.md). The PostgreSQL facts run only when
// HIREZERO_TEST_POSTGRES names a disposable server; each one works in its own schema, dropped afterwards.
public sealed class StoreDatabaseTests : IAsyncDisposable
{
    private const string Owner = "owner@example.invalid";
    private const string ServerVariable = "HIREZERO_TEST_POSTGRES";
    private readonly TemporaryRoot _root = new("store-database-");
    private readonly string _schema = "hz_" + Guid.NewGuid().ToString("N")[..16];
    private PostgresStoreDatabase? _postgres;

    private static string? Server => Environment.GetEnvironmentVariable(ServerVariable);

    public async ValueTask DisposeAsync()
    {
        if (_postgres is not null)
        {
            _postgres.Dispose();
            await using var admin = new NpgsqlConnection(Server);
            await admin.OpenAsync();
            await using var drop = new NpgsqlCommand($"DROP SCHEMA IF EXISTS {_schema} CASCADE", admin);
            await drop.ExecuteNonQueryAsync();
        }
        SqliteConnection.ClearAllPools();
        await _root.DisposeAsync();
    }

    private PostgresStoreDatabase Postgres()
    {
        Assert.SkipWhen(Server is null, "Set " + ServerVariable + " to a disposable PostgreSQL server to run this.");
        using (var admin = new NpgsqlConnection(Server))
        {
            admin.Open();
            using var create = new NpgsqlCommand($"CREATE SCHEMA {_schema}", admin);
            create.ExecuteNonQuery();
        }
        return _postgres = new PostgresStoreDatabase(
            new NpgsqlConnectionStringBuilder(Server) { SearchPath = _schema }.ToString(),
            _root.Path
        );
    }

    private static CompanyCommand Cmd(string action) => new(Guid.NewGuid().ToString("D"), action);

    private static (string Owner, int Version, string Checksum)[] Ledger(StoreDatabase database)
    {
        using var db = new StoreConnection(database.Open(), database);
        return db.Rows(
            "SELECT owner,version,checksum FROM module_schema_migrations ORDER BY owner,version",
            r => (r.GetString(0), Convert.ToInt32(r.GetValue(1)), r.GetString(2))
        );
    }

    [Fact]
    public void PortableStatementsTranslateToPostgres()
    {
        Assert.Equal(
            "SELECT payload FROM co_tasks WHERE company_id=@p0 AND id=@p1",
            PostgresStoreDatabase.Rewrite("SELECT payload FROM co_tasks WHERE company_id=$0 AND id=$1")
        );
        Assert.Equal(
            "CREATE TABLE t(seq BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,company_id TEXT NOT NULL)",
            PostgresStoreDatabase.Rewrite(
                "CREATE TABLE t(seq INTEGER PRIMARY KEY AUTOINCREMENT,company_id TEXT NOT NULL)"
            )
        );
        Assert.Equal(
            "CREATE UNIQUE INDEX i ON co_messages(company_id,((payload::jsonb)->>'sequence'))",
            PostgresStoreDatabase.Rewrite(
                "CREATE UNIQUE INDEX i ON co_messages(company_id,json_extract(payload,'$.sequence'))"
            )
        );
        Assert.StartsWith(
            "CREATE TABLE co_tasks(rowid BIGINT GENERATED ALWAYS AS IDENTITY,id TEXT NOT NULL,company_id TEXT NOT NULL,",
            PostgresStoreDatabase.Rewrite(
                "CREATE TABLE co_tasks(id TEXT NOT NULL,company_id TEXT NOT NULL,parent_id TEXT)"
            )
        );
    }

    [Fact]
    public void ACompanyLedgerFromBeforeTheOneFrameworkIsAdopted()
    {
        var path = Path.Combine(_root.Path, "company.sqlite");
        var store = new CompanyStore(path, Owner, CompanyWorkspace.Definitions());
        store.Apply(Cmd("department.create") with { Name = "Kept" });
        var steps = Ledger(new SqliteStoreDatabase(path));
        // Put the database back the way an older build left it: its own ledger, no shared one.
        using (
            var db = new SqliteConnection(
                new SqliteConnectionStringBuilder { DataSource = path, Pooling = false }.ToString()
            )
        )
        {
            db.Open();
            using var older = db.CreateCommand();
            older.CommandText =
                "CREATE TABLE company_schema_migrations(version INTEGER PRIMARY KEY, checksum TEXT NOT NULL); INSERT INTO company_schema_migrations SELECT version,checksum FROM module_schema_migrations WHERE owner='company'; DROP TABLE module_schema_migrations";
            older.ExecuteNonQuery();
        }

        var reopened = new CompanyStore(path, Owner, CompanyWorkspace.Definitions());

        Assert.Equal(steps, Ledger(new SqliteStoreDatabase(path)));
        using var check = new StoreConnection(reopened.Database.Open(), reopened.Database);
        Assert.False(reopened.Database.TableExists(check, "company_schema_migrations"));
        Assert.Equal(
            1,
            JsonSerializer
                .SerializeToElement(reopened.Dashboard(), CompanyJson.Options)
                .GetProperty("departments")
                .GetArrayLength()
        );
    }

    [Fact]
    public Task TheCompanyChecksPassOnPostgres() => CompanyInlineChecks.RunAsync(_root.Path, Postgres());

    [Fact]
    public Task RequestsActInTheirCompanyOnPostgres() =>
        CompanyTenancyTests.RequestsActInTheCompanyTheyName(_root.Path, Postgres());

    [Fact]
    public void PostgresKeepsTheSameLedgerCompaniesAndAuditChain()
    {
        var database = Postgres();
        var first = new CompanyStore(database, Owner, CompanyWorkspace.Definitions());
        var second = new CompanyStore(database, Owner, CompanyWorkspace.Definitions(), companyId: "co-fictional-two");
        first.Apply(Cmd("department.create") with { Name = "First only" });
        second.Apply(Cmd("member.invite") with { Body = "second@example.invalid", Decision = "viewer" });
        first.Record(
            new ToolCallRecord(
                DateTimeOffset.UtcNow,
                "git.read",
                "read",
                "developer",
                null,
                null,
                new string('a', 64),
                null,
                "completed",
                null
            )
        );

        // The same steps, recorded with the same checksums as on SQLite.
        var sqlite = new SqliteStoreDatabase(Path.Combine(_root.Path, "company.sqlite"));
        _ = new CompanyStore(sqlite, Owner, CompanyWorkspace.Definitions());
        Assert.Equal(Ledger(sqlite), Ledger(database));

        Assert.Equal(
            ["co-fictional-two", CompanyStore.DefaultCompanyId],
            CompanyStore.Companies(database).Select(c => c.Id)
        );
        Assert.Single(first.Members());
        Assert.Equal(2, second.Members().Length);
        Assert.True(first.VerifyAudit().Intact);
        Assert.True(second.VerifyAudit().Intact);
        Assert.Contains(first.AuditEntries(), e => e.Kind == "tool-call");

        using (var db = new StoreConnection(database.Open(), database))
            db.Execute(
                "UPDATE co_audit SET body=body || ' ' WHERE company_id=$0 AND seq=2",
                CompanyStore.DefaultCompanyId
            );
        Assert.False(first.VerifyAudit().Intact);
        Assert.True(second.VerifyAudit().Intact);
    }
}
