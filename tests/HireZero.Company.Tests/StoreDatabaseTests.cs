    [Fact]
    public void PostgresKeepsTheSameLedgerCompaniesAndAuditChain()
    {
        var database = Postgres();
        var first = new CompanyStore(database, Owner, CompanyWorkspace.Definitions());
        var second = new CompanyStore(database, Owner, CompanyWorkspace.Definitions(), companyId: "co-fictional-two");
        first.Apply(Cmd("department.create") with { Name = "First only" });
        second.Apply(Cmd("member.invite") with { Body = "second@example.invalid", Decision = "viewer" });
        first.Record(
            new ToolCallRecord(
                DateTimeOffset.UtcNow,
                "git.read",
                "read",
                "developer",
                null,
                null,
                new string('a', 64),
                null,
                "completed",
                null
            )
        );

        // The same steps, recorded with the same checksums as on SQLite.
        var sqlite = new SqliteStoreDatabase(Path.Combine(_root.Path, "company.sqlite"));
        _ = new CompanyStore(sqlite, Owner, CompanyWorkspace.Definitions());
        Assert.Equal(Ledger(sqlite), Ledger(database));

        Assert.Equal(
            ["co-fictional-two", CompanyStore.DefaultCompanyId],
            CompanyStore.Companies(database).Select(c => c.Id)
        );
        Assert.Single(first.Members());
        Assert.Equal(2, second.Members().Length);
        Assert.True(first.VerifyAudit().Intact);
        Assert.True(second.VerifyAudit().Intact);
        Assert.Contains(first.AuditEntries(), e => e.Kind == "tool-call");

        using (var db = new StoreConnection(database.Open(), database))
            db.Execute(
                "UPDATE co_audit SET body=body || ' ' WHERE company_id=$0 AND seq=2",
                CompanyStore.DefaultCompanyId
            );
        Assert.False(first.VerifyAudit().Intact);
        Assert.True(second.VerifyAudit().Intact);
    }

    [Fact]
    public void ApprovedContextAndRetiredSourceDeletionStayCompanyScopedOnPostgres()
    {
        var database = Postgres();
        var first = new CompanyStore(
            database,
            Owner,
            CompanyWorkspace.Definitions(),
            measuredRuntimeIdentity: "fictional-runtime"
        );
        var second = new CompanyStore(
            database,
            Owner,
            CompanyWorkspace.Definitions(),
            companyId: "co-context-neighbor"
        );
        T Apply<T>(CompanyStore store, CompanyCommand command) => CompanyJson.Decode<T>(store.Apply(command));
        var work = MeasuredQueueChecks.Seed(first);
        var documentSave = Cmd("document.save") with
        {
            Body = CompanyJson.Encode(new CompanyDocumentInput("Cobalt guide", "Fictional cobalt document evidence.")),
        };
        var document = Apply<CompanyDocument>(first, documentSave);
        document = Apply<CompanyDocument>(
            first,
            Cmd("document.review") with
            {
                Id = document.Id,
                ExpectedVersion = document.Version,
                Digest = document.Digest,
                Decision = "approve",
            }
        );
        var memorySave = Cmd("memory.save") with
        {
            Body = CompanyJson.Encode(
                new CompanyMemoryInput(
                    "decision",
                    "Cobalt decision",
                    "Fictional cobalt memory evidence.",
                    "Owner chose demonstrations."
                )
            ),
        };
        var memory = Apply<CompanyMemoryItem>(first, memorySave);
        memory = Apply<CompanyMemoryItem>(
            first,
            Cmd("memory.review") with
            {
                Id = memory.Id,
                ExpectedVersion = memory.Version,
                Digest = memory.Digest,
                Decision = "approve",
            }
        );
        var neighbor = Apply<CompanyMemoryItem>(second, memorySave with { RequestId = Guid.NewGuid().ToString("D") });
        Assert.Single(first.RetrieveDocuments("cobalt").Excerpts);
        Assert.Single(first.RetrieveMemory("cobalt").Items);
        Assert.Empty(second.RetrieveDocuments("cobalt").Excerpts);
        Assert.Empty(second.RetrieveMemory("cobalt").Items);
        using var prepared = JsonDocument.Parse(
            first.Apply(
                Cmd("conversation.prepare") with
                {
                    EmployeeId = work.EmployeeId,
                    ThreadId = work.ThreadId,
                    Scope = "employee",
                    Body = "Draft a cobalt campaign note",
                    CreditAllowance = 1,
                }
            )
        );
        var attempt = prepared.RootElement.GetProperty("attempt").Deserialize<CompanyAttempt>(CompanyJson.Options)!;
        var packet = CompanyJson.Encode(first.TextCall(attempt.Id));
        Assert.Contains("Fictional cobalt document evidence.", packet);
        Assert.Contains("Fictional cobalt memory evidence.", packet);
        document = Apply<CompanyDocument>(
            first,
            Cmd("document.review") with
            {
                Id = document.Id,
                ExpectedVersion = document.Version,
                Digest = document.Digest,
                Decision = "revoke",
            }
        );
        memory = Apply<CompanyMemoryItem>(
            first,
            Cmd("memory.review") with
            {
                Id = memory.Id,
                ExpectedVersion = memory.Version,
                Digest = memory.Digest,
                Decision = "revoke",
            }
        );
        var deletion = Cmd("memory.source.delete") with
        {
            Id = memory.Id,
            ExpectedVersion = memory.Version,
            Digest = memory.Digest,
            Decision = "delete-retired-source",
        };
        Assert.Equal(404, Assert.Throws<WorkspaceException>(() => second.Apply(deletion)).Status);
        var deletedMemory = Apply<CompanyMemoryItem>(first, deletion);
        var deletedDocument = Apply<CompanyDocument>(
            first,
            Cmd("document.source.delete") with
            {
                Id = document.Id,
                ExpectedVersion = document.Version,
                Digest = document.Digest,
                Decision = "delete-revoked-source",
            }
        );
        Assert.Equal("retired-source", deletedMemory.DeletionScope);
        Assert.Empty(deletedMemory.Definition.Statement);
        Assert.Empty(deletedDocument.Text);
        Assert.Empty(first.RetrieveDocuments("cobalt").Excerpts);
        Assert.Empty(first.RetrieveMemory("cobalt").Items);
        Assert.Equal(CompanyJson.Encode(deletedMemory), first.Apply(memorySave, out var replayed));
        Assert.False(replayed);
        Assert.Equal(CompanyJson.Encode(deletedDocument), first.Apply(documentSave, out replayed));
        Assert.False(replayed);
        Assert.Throws<WorkspaceException>(() =>
            first.Apply(
                Cmd("measured.run") with
                {
                    Id = attempt.Id,
                    ExpectedVersion = attempt.Version,
                    Digest = attempt.Measured!.Digest,
                    Decision = "accept-soft-limits",
                }
            )
        );
        Assert.Equal(packet, CompanyJson.Encode(first.TextCall(attempt.Id)));
        Assert.Equal(neighbor, second.Memory(neighbor.Id).Memory);
        Assert.True(first.VerifyAudit().Intact);
        Assert.True(second.VerifyAudit().Intact);
    }

    // The password is a secret file, not part of the connection string; rotating the role's password and the file
    // together keeps the host connecting, with no restart (docs/adr/0027-secrets-from-files.md).
    [Fact]
    public void ARotatedDatabasePasswordIsPickedUpWithoutARestart()
    {
        Postgres();
        var role = _schema + "_role";
        string NewPassword() => Convert.ToHexString(System.Security.Cryptography.RandomNumberGenerator.GetBytes(16));
        var password = NewPassword();
        Admin($"CREATE ROLE {role} LOGIN PASSWORD '{password}'; GRANT ALL ON SCHEMA {_schema} TO {role}");
        var file = Path.Combine(_root.Path, "database-password");
        File.WriteAllText(file, password + "\n");
        var secrets = new SecretSource(
            name => name == PostgresStoreDatabase.PasswordVariable + "_FILE" ? file : null,
            []
        );
        var connection = new NpgsqlConnectionStringBuilder(Server)
        {
            Username = role,
            Password = null,
            SearchPath = _schema,
            Pooling = false,
        }.ToString();
        using var database = new PostgresStoreDatabase(
            connection,
            _root.Path,
            () => secrets.Read(PostgresStoreDatabase.PasswordVariable),
            TimeSpan.FromMilliseconds(200)
        );
        var store = new CompanyStore(database, Owner, CompanyWorkspace.Definitions());
        store.Apply(Cmd("department.create") with { Name = "Before rotation" });

        var rotated = NewPassword();
        Admin($"ALTER ROLE {role} PASSWORD '{rotated}'");
        File.WriteAllText(file, rotated + "\n");
        // The server really checks passwords: the old one no longer opens a connection.
        Assert.ThrowsAny<NpgsqlException>(() =>
        {
            using var old = new NpgsqlConnection(
                new NpgsqlConnectionStringBuilder(connection) { Password = password }.ToString()
            );
            old.Open();
        });
        Thread.Sleep(TimeSpan.FromSeconds(1));
        store.Apply(Cmd("department.create") with { Name = "After rotation" });

        Assert.Equal(
            2,
            JsonSerializer
                .SerializeToElement(store.Dashboard(), CompanyJson.Options)
                .GetProperty("departments")
                .GetArrayLength()
        );
    }
