using System.Collections.Concurrent;
using System.Data.Common;
using System.Text.RegularExpressions;
using Npgsql;

namespace HireZero.Integrations.Postgres;

// Company data in PostgreSQL for hosted installs (docs/adr/0025-one-schema-two-databases.md). The portable statements
// are translated, not rewritten per database: parameters become named ones, an autoincrement key becomes an identity,
// a JSON field becomes a jsonb operator, and each payload table gains the insertion order SQLite keeps as its rowid.
// A write transaction holds a transaction-scoped advisory lock on its scope (one company, or the schema), which gives
// the same one-writer-per-company guarantee as SQLite's single writer.
public sealed partial class PostgresStoreDatabase : StoreDatabase, IDisposable
{
    public const string ConnectionVariable = "HIREZERO_DATABASE";

    private readonly NpgsqlDataSource _source;
    private readonly string _keyDirectory;
    private readonly ConcurrentDictionary<string, string> _translated = new(StringComparer.Ordinal);

    public PostgresStoreDatabase(string connectionString, string keyDirectory)
    {
        _source = NpgsqlDataSource.Create(connectionString);
        _keyDirectory = Path.GetFullPath(keyDirectory);
    }

    public override string KeyDirectory
    {
        get
        {
            Directory.CreateDirectory(_keyDirectory);
            return _keyDirectory;
        }
    }

    public override DbConnection Open() => _source.OpenConnection();

    public override void Begin(StoreConnection db, string scope)
    {
        db.Execute("BEGIN");
        try
        {
            // A writer that cannot get its scope within the bound fails, as SQLite's busy timeout does.
            db.Execute("SET LOCAL lock_timeout = '5s'");
            db.Execute("SELECT pg_advisory_xact_lock(hashtext($0))", "hirezero:" + scope);
        }
        catch
        {
            db.Execute("ROLLBACK");
            throw;
        }
    }

    public override bool TableExists(StoreConnection db, string table) =>
        db.Scalar(
            "SELECT count(*) FROM information_schema.tables WHERE table_schema=current_schema() AND table_name=$0",
            table
        ) != "0";

    public override string Parameter(int index) => "p" + index;

    public override string Translate(string sql) => _translated.GetOrAdd(sql, Rewrite);

    public static string Rewrite(string sql)
    {
        sql = JsonField().Replace(sql, "(($1::jsonb)->>'$2')");
        sql = sql.Replace(
            "INTEGER PRIMARY KEY AUTOINCREMENT",
            "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY",
            StringComparison.Ordinal
        );
        sql = sql.Replace(
            "(id TEXT NOT NULL,company_id TEXT NOT NULL,",
            "(rowid BIGINT GENERATED ALWAYS AS IDENTITY,id TEXT NOT NULL,company_id TEXT NOT NULL,",
            StringComparison.Ordinal
        );
        return Parameters().Replace(sql, "@p$1");
    }

    public void Dispose() => _source.Dispose();

    [GeneratedRegex(@"json_extract\((\w+),'\$\.(\w+)'\)")]
    private static partial Regex JsonField();

    [GeneratedRegex(@"\$(\d+)")]
    private static partial Regex Parameters();
}
